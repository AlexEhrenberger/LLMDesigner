import Foundation
import LLMDProtocol

/// The tab completion, made from the schemas.
enum Completion {
    static func zsh(actions: [ActionDescriptor]) -> String {
        var cases = ""
        for action in actions {
            let words = action.id.split(separator: ".").map { DynamicCommand.kebab(String($0)) }.joined(separator: " ")
            let options = (action.input.properties ?? [:]).keys.sorted().map { "--" + DynamicCommand.kebab($0) }.joined(separator: " ")
            cases += "    \"\(words)\") opts=(\(options));;\n"
        }
        let paths = actions.map { "\"" + $0.id.split(separator: ".").map { DynamicCommand.kebab(String($0)) }.joined(separator: " ") + "\"" }.joined(separator: " ")
        return """
        #compdef llmd
        # Generated by `llmd completion zsh`. Install: llmd completion zsh > "${fpath[1]}/_llmd"
        _llmd() {
          local -a paths next opts
          paths=(\(paths) "status" "actions" "describe" "call" "batch" "watch" "completion" "mcp")
          local typed="${(j: :)${words[2,CURRENT-1]:#-*}}"
          next=()
          local entry
          for entry in $paths; do
            if [[ -z "$typed" ]]; then next+=("${entry%% *}")
            elif [[ "$entry" == "$typed "* ]]; then
              local tail="${entry#$typed }"
              next+=("${tail%% *}")
            fi
          done
          opts=(--json --quiet --stdin --stdin-to --no-launch --run)
          case "$typed" in
        \(cases)  esac
          if [[ "$PREFIX" == -* ]]; then compadd -- $opts; else compadd -- ${(u)next}; fi
        }
        _llmd "$@"
        """
    }
}
